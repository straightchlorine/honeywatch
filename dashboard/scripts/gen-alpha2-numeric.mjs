// One-shot codegen: ISO 3166-1 alpha-2 -> numeric id (zero-padded 3-char
// string), matching the world-atlas countries-110m TopoJSON feature ids.
//
//   node scripts/gen-alpha2-numeric.mjs
//
// NOT a build step. Re-run only to refresh src/components/map/alpha2-to-numeric.ts
// (e.g. after bumping i18n-iso-countries). The generated table is committed so
// the runtime carries no i18n dependency.
import { writeFileSync } from 'node:fs'

import iso from 'i18n-iso-countries'

const alpha2 = Object.keys(iso.getAlpha2Codes())
const entries = alpha2
  .map((a2) => [a2, iso.alpha2ToNumeric(a2)])
  .filter(([, numeric]) => Boolean(numeric))
  .sort((a, b) => a[0].localeCompare(b[0]))

const rows = entries.map(([a2, numeric]) => `  ${a2}: '${numeric}',`).join('\n')

const out = `// AUTO-GENERATED by scripts/gen-alpha2-numeric.mjs -- do not edit by hand.
//
// ISO 3166-1 alpha-2 -> numeric id, zero-padded to match world-atlas
// countries-110m TopoJSON feature ids (e.g. AF -> '004'). Join as STRINGS:
// parseInt('004') === 4 would silently drop every country numbered under 100.
export const ALPHA2_TO_NUMERIC: Readonly<Record<string, string>> = Object.freeze({
${rows}
})
`

writeFileSync(new URL('../src/components/map/alpha2-to-numeric.ts', import.meta.url), out)
console.log(`wrote ${entries.length} alpha-2 -> numeric entries`)
